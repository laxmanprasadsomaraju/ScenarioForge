describe('history: tamper detection on every read', () => {
  async function saved() {
    const ctx = setup();
    await ctx.store.saveRun(ALICE, ctx.rehearsal, submit(ctx.rehearsal.scenario, COSTLY, 's1'));
    return { ...ctx, key: runKey(ALICE, 's1') };
  }

  it('an edited evaluation is TAMPERED (digest)', async () => {
    const { store, storage, key } = await saved();
    await edit<RunRecord>(storage, key, (r) => {
      r.audit.evaluation!.metCount = 4;
    });
    expect(await store.getRun(ALICE, 's1')).toEqual({
      status: 'TAMPERED',
      problems: ['record does not match its index digest'],
    });
  });

  it('an edited evaluation with a fixed-up digest is still TAMPERED (replay)', async () => {
    const { store, storage, key } = await saved();
    await editConsistently<RunRecord>(storage, ALICE, key, 's1', (r) => {
      r.audit.evaluation!.objectives.forEach((o) => (o.status = 'met'));
      r.audit.evaluation!.metCount = 4;
    });
    const got = await store.getRun(ALICE, 's1');
    expect(got.status).toBe('TAMPERED');
    expect(got.status === 'TAMPERED' && got.problems).toContain(
      'evaluation does not match the replay',
    );
  });

  it('an edited scenario snapshot is TAMPERED (fingerprint)', async () => {
    const { store, storage, key } = await saved();
    await editConsistently<RunRecord>(storage, ALICE, key, 's1', (r) => {
      r.scenario.objectives[0]!.label = 'Anything';
    });
    const got = await store.getRun(ALICE, 's1');
    expect(got.status === 'TAMPERED' && got.problems).toContain(
      'scenario snapshot does not match its fingerprint',
    );
  });

  it('an unknown engine version or format is UNVERIFIABLE, a missing record too', async () => {
    const { store, storage, key } = await saved();
    await editConsistently<RunRecord>(storage, ALICE, key, 's1', (r) => {
      r.engineVersion = 99;
    });
    expect(await store.getRun(ALICE, 's1')).toMatchObject({ status: 'UNVERIFIABLE' });

    await editConsistently<Record<string, unknown>>(storage, ALICE, key, 's1', (r) => {
      r.schemaVersion = 2;
    });
    expect(await store.getRun(ALICE, 's1')).toMatchObject({ status: 'UNVERIFIABLE' });

    await storage.delete(key);
    expect(await store.getRun(ALICE, 's1')).toEqual({
      status: 'UNVERIFIABLE',
      reason: 'The stored run record is missing.',
    });
  });
});

describe('history: isolation by installation and account', () => {
  it("a user never sees another user's runs", async () => {
    const { store, rehearsal } = setup();
    await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's1'));
    expect(await store.listRuns(BOB)).toEqual({ status: 'OK', items: [], pruned: [] });
    expect(await store.getRun(BOB, 's1')).toEqual({ status: 'NOT_FOUND' });
    const otherSite = { ...ALICE, installation: 'ari:cloud:jira::site/other' };
    expect(await store.getRun(otherSite, 's1')).toEqual({ status: 'NOT_FOUND' });
  });

  it("a record copied into another user's keys is TAMPERED, not shown", async () => {
    const { store, storage, rehearsal } = setup();
    await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's1'));
    const record = (await storage.get<RunRecord>(runKey(ALICE, 's1')))!.value;
    const index = (await storage.get<HistoryIndex>(indexKey(ALICE)))!.value;
    await storage.set(runKey(BOB, 's1'), record, null);
    await storage.set(indexKey(BOB), index, null);
    const got = await store.getRun(BOB, 's1');
    expect(got.status === 'TAMPERED' && got.problems).toContain(
      'record belongs to another user or installation',
    );
  });

  it('keys are scoped, valid and injective even with separators in ids', () => {
    const a = runKey({ installation: 'x', accountId: 'y:z' }, 'r');
    const b = runKey({ installation: 'x:y', accountId: 'z' }, 'r');
    expect(a).not.toBe(b);
    for (const key of [indexKey(ALICE), runKey(ALICE, 's1'), retestKey(ALICE, 's2'), a, b]) {
      expect(KEY_PATTERN.test(key)).toBe(true);
      expect(key.length).toBeLessThanOrEqual(500);
    }
    expect(runKey(ALICE, 's1').startsWith(indexKey(ALICE).replace(/index$/, ''))).toBe(true);
    expect(indexKey(ALICE)).not.toBe(indexKey(BOB));
    expect(() => indexKey({ installation: '', accountId: 'a' })).toThrow();
  });
});

describe('history: retention', () => {
  it(`keeps at most ${MAX_RUNS_PER_USER} runs, pruning the oldest and reporting them`, async () => {
    const { store, storage, rehearsal, clock } = setup();
    const results = [];
    for (let i = 0; i < MAX_RUNS_PER_USER + 2; i++) {
      clock.now = T0 + i * 60_000;
      const id = `run-${String(i).padStart(2, '0')}`;
      results.push(await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, id)));
    }
    expect(results.slice(0, MAX_RUNS_PER_USER).every((r) => r.status === 'SAVED')).toBe(true);
    expect(results[MAX_RUNS_PER_USER]).toMatchObject({
      status: 'SAVED',
      pruned: [{ id: 'run-00', kind: 'run', reason: 'count' }],
    });
    expect(results[MAX_RUNS_PER_USER + 1]).toMatchObject({
      pruned: [{ id: 'run-01', reason: 'count' }],
    });
    const list = await store.listRuns(ALICE);
    expect(list.status === 'OK' && list.items.length).toBe(MAX_RUNS_PER_USER);
    expect(list.status === 'OK' && list.items.at(-1)!.run.id).toBe('run-02');
    expect(await storage.get(runKey(ALICE, 'run-00'))).toBeUndefined();
    expect(await storage.get(runKey(ALICE, 'run-01'))).toBeUndefined();
    expect(await store.getRun(ALICE, 'run-00')).toEqual({ status: 'NOT_FOUND' });
  });

  it(`prunes runs older than ${MAX_AGE_DAYS} days with their retests, on list`, async () => {
    const { store, storage, rehearsal, clock } = setup();
    await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 'old'));
    const fixed = buildRetest(
      rehearsal.scenario,
      replaySession(rehearsal.scenario, COSTLY, 'old', START),
      ['rem-step'],
      rehearsal.remediation!,
    );
    clock.now += 1000;
    await store.saveRetest(ALICE, {
      originalRunId: 'old',
      remediationIds: ['rem-step'],
      submission: submit(fixed, FIXED_PATH, 'old-retest'),
    });
    clock.now = T0 + 10 * DAY;
    await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 'newer'));

    clock.now = T0 + MAX_AGE_DAYS * DAY; // exactly 90 days: kept
    let list = await store.listRuns(ALICE);
    expect(list.status === 'OK' && list.pruned).toEqual([]);

    clock.now = T0 + MAX_AGE_DAYS * DAY + 1;
    expect(await store.getRun(ALICE, 'old')).toEqual({ status: 'NOT_FOUND' });
    list = await store.listRuns(ALICE);
    expect(list).toMatchObject({
      status: 'OK',
      pruned: [
        { id: 'old', kind: 'run', reason: 'age' },
        { id: 'old-retest', kind: 'retest', retestOf: 'old', reason: 'age' },
      ],
    });
    expect(list.status === 'OK' && list.items.map((i) => i.run.id)).toEqual(['newer']);
    expect(await storage.get(runKey(ALICE, 'old'))).toBeUndefined();
    expect(await storage.get(retestKey(ALICE, 'old-retest'))).toBeUndefined();
    expect((await storage.get<HistoryIndex>(indexKey(ALICE)))!.value.entries).toHaveLength(1);
  });

  it('prunes by age on write too', async () => {
    const { store, rehearsal, clock } = setup();
    await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 'old'));
    clock.now = T0 + 100 * DAY;
    const saved = await store.saveRun(
      ALICE,
      rehearsal,
      submit(rehearsal.scenario, COSTLY, 'today'),
    );
    expect(saved).toMatchObject({ status: 'SAVED', pruned: [{ id: 'old', reason: 'age' }] });
  });
});

describe('history: MC-62 retest before/after', () => {
  async function original() {
    const ctx = setup();
    const { store, rehearsal, clock } = ctx;
    expect(
      (await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's1'))).status,
    ).toBe('SAVED');
    clock.now += 30 * 60_000;
    // The browser builds the same retest scenario to play it.
    const fixed = buildRetest(
      rehearsal.scenario,
      replaySession(rehearsal.scenario, COSTLY, 's1', START),
      ['rem-step'],
      rehearsal.remediation!,
    );
    return { ...ctx, fixed };
  }

  it('fix + retest following the updated step → resolved, before/after stored and verified', async () => {
    const { store, fixed, clock } = await original();
    const saved = await store.saveRetest(ALICE, {
      originalRunId: 's1',
      remediationIds: ['rem-step'],
      submission: submit(fixed, FIXED_PATH, 's1-retest'),
    });
    expect(saved).toMatchObject({ status: 'SAVED', id: 's1-retest' });

    const cmp = await store.getComparison(ALICE, 's1-retest');
    expect(cmp.status).toBe('OK');
    if (cmp.status !== 'OK') return;
    expect(cmp.comparison).toMatchObject({
      id: 's1-retest',
      originalSessionId: 's1',
      retestSessionId: 's1-retest',
      outcome: 'resolved',
      comparedAt: new Date(clock.now).toISOString(),
    });
    expect(cmp.comparison.gaps[0]).toMatchObject({ exercised: true, decisionsEffective: true });
    expect(cmp.original.evaluation.metCount).toBe(2);
    expect(cmp.retest.evaluation.metCount).toBe(4);
    expect(cmp.retest.scenario.version).toBe(2);
    expect(cmp.retest.fixSet).toEqual({
      remediationIds: ['rem-step'],
      approvedBy: ALICE.accountId,
      approvedAt: new Date(clock.now).toISOString(),
    });
    const restore = cmp.comparison.gaps[0]!.objectives.find((o) => o.objectiveId === 'obj-restore');
    expect(restore).toEqual({ objectiveId: 'obj-restore', original: 'missed', retest: 'met' });

    const run = await store.getRun(ALICE, 's1');
    expect(run.status === 'OK' && run.run.retestIds).toEqual(['s1-retest']);
    const list = await store.listRuns(ALICE);
    expect(list.status === 'OK' && list.items[0]!.retests).toMatchObject([
      { id: 's1-retest', kind: 'retest', retestOf: 's1', outcome: 'resolved', metCount: 4 },
    ]);
  });

  it('a retest that avoids the step is stored as inconclusive', async () => {
    const { store, fixed } = await original();
    await store.saveRetest(ALICE, {
      originalRunId: 's1',
      remediationIds: ['rem-step'],
      submission: submit(fixed, ['check-change', 'notify-now', 'use-replacement'], 'r2'),
    });
    const cmp = await store.getComparison(ALICE, 'r2');
    expect(cmp.status === 'OK' && cmp.comparison.outcome).toBe('inconclusive');
  });

  it('rejects a retest played on a scenario other than original + approved fixes', async () => {
    const { store, rehearsal, fixed } = await original();
    // Claims rem-change-check but played the rem-step variant.
    expect(
      await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: ['rem-change-check'],
        submission: submit(fixed, FIXED_PATH, 'r2'),
      }),
    ).toMatchObject({ reason: 'SCENARIO_MISMATCH' });
    expect(
      await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: ['no-such-fix'],
        submission: submit(rehearsal.scenario, COSTLY, 'r3'),
      }),
    ).toMatchObject({ reason: 'INVALID_FIXES' });
    const forged = submit(fixed, ['check-change', 'notify-now', 'use-replacement'], 'r4');
    forged.evaluation = { ...forged.evaluation, elapsedMinutes: 1 };
    expect(
      await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: ['rem-step'],
        submission: forged,
      }),
    ).toMatchObject({ reason: 'EVALUATION_MISMATCH' });
    expect(
      await store.saveRetest(BOB, {
        originalRunId: 's1',
        remediationIds: ['rem-step'],
        submission: submit(fixed, FIXED_PATH, 'r5'),
      }),
    ).toMatchObject({ reason: 'ORIGINAL_NOT_FOUND' });
  });

  it('a tampered original refuses retests; a tampered comparison is TAMPERED', async () => {
    const { store, storage, fixed } = await original();
    await store.saveRetest(ALICE, {
      originalRunId: 's1',
      remediationIds: ['rem-step'],
      submission: submit(fixed, FIXED_PATH, 'r1'),
    });
    await editConsistently<RetestRecord>(storage, ALICE, retestKey(ALICE, 'r1'), 'r1', (r) => {
      r.comparison.outcome = 'still-failing';
    });
    expect(await store.getComparison(ALICE, 'r1')).toMatchObject({
      status: 'TAMPERED',
      problems: ['stored comparison does not match the recomputed comparison'],
    });

    await editConsistently<RetestRecord>(storage, ALICE, retestKey(ALICE, 'r1'), 'r1', (r) => {
      r.fixSet.remediationIds = ['rem-change-check'];
    });
    expect(await store.getComparison(ALICE, 'r1')).toMatchObject({ status: 'TAMPERED' });

    await edit<RunRecord>(storage, runKey(ALICE, 's1'), (r) => {
      r.audit.elapsedMinutes = 1;
    });
    expect(await store.getComparison(ALICE, 'r1')).toMatchObject({ status: 'TAMPERED' });
    expect(
      await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: ['rem-step'],
        submission: submit(fixed, FIXED_PATH, 'r2'),
      }),
    ).toMatchObject({ reason: 'ORIGINAL_NOT_VERIFIED' });
  });

  it(`keeps at most ${MAX_RETESTS_PER_RUN} retests per run; BOB cannot read ALICE's`, async () => {
    const { store, fixed } = await original();
    for (let i = 0; i < MAX_RETESTS_PER_RUN; i++) {
      const res = await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: ['rem-step'],
        submission: submit(fixed, FIXED_PATH, `r${i}`),
      });
      expect(res.status).toBe('SAVED');
    }
    expect(
      await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: ['rem-step'],
        submission: submit(fixed, FIXED_PATH, 'one-more'),
      }),
    ).toMatchObject({ reason: 'RETEST_LIMIT' });
    expect(await store.getComparison(BOB, 'r0')).toEqual({ status: 'NOT_FOUND' });
  });
});

/** Adapter wrapper that can throw or report conflicts on demand. */
class FlakyStorage extends InMemoryStorage {
  failGet = false;
  failSet: (key: string) => boolean = () => false;
  conflictsLeft = 0;
  /** Runs once, just before the next index write (to interleave a concurrent writer). */
  beforeIndexSet: (() => Promise<unknown>) | null = null;

  override async get<T>(key: string): Promise<Versioned<T> | undefined> {
    if (this.failGet) throw new Error('storage unreachable');
    return super.get<T>(key);
  }

  override async set<T>(key: string, value: T, expected: number | null): Promise<WriteResult> {
    if (this.failSet(key)) throw new Error('storage unreachable');
    if (key.endsWith(':index') && this.beforeIndexSet) {
      const hook = this.beforeIndexSet;
      this.beforeIndexSet = null;
      await hook();
    }
    if (key.endsWith(':index') && this.conflictsLeft > 0) {
      this.conflictsLeft--;
      return { ok: false, reason: 'CONFLICT' };
    }
    return super.set(key, value, expected);
  }
}

describe('history: failure semantics', () => {
  it('storage errors are UNAVAILABLE, never an empty list', async () => {
    const storage = new FlakyStorage();
    const { store, rehearsal } = setup(storage);
    await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's1'));
    storage.failGet = true;
    expect(await store.listRuns(ALICE)).toEqual({ status: 'UNAVAILABLE' });
    expect(await store.getRun(ALICE, 's1')).toEqual({ status: 'UNAVAILABLE' });
    expect(await store.getComparison(ALICE, 'r1')).toEqual({ status: 'UNAVAILABLE' });
    expect(await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's2'))).toEqual(
      { status: 'UNAVAILABLE' },
    );
    expect(
      await store.saveRetest(ALICE, {
        originalRunId: 's1',
        remediationIds: [],
        submission: submit(rehearsal.scenario, COSTLY, 'r1'),
      }),
    ).toEqual({ status: 'UNAVAILABLE' });
  });

  it('a malformed index is UNAVAILABLE, not an empty list', async () => {
    const { store, storage } = setup();
    await storage.set(indexKey(ALICE), { garbage: true }, null);
    expect(await store.listRuns(ALICE)).toEqual({ status: 'UNAVAILABLE' });
  });

  it('an index write failure leaves no orphan record', async () => {
    const storage = new FlakyStorage();
    const { store, rehearsal } = setup(storage);
    storage.failSet = (key) => key.endsWith(':index');
    expect(await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's1'))).toEqual(
      { status: 'UNAVAILABLE' },
    );
    expect(storage.keys()).toEqual([]);
  });

  it(`retries index conflicts up to ${MAX_WRITE_ATTEMPTS} attempts`, async () => {
    const storage = new FlakyStorage();
    const { store, rehearsal } = setup(storage);
    storage.conflictsLeft = MAX_WRITE_ATTEMPTS - 1;
    expect(
      (await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's1'))).status,
    ).toBe('SAVED');
    expect((await store.getRun(ALICE, 's1')).status).toBe('OK');

    storage.conflictsLeft = MAX_WRITE_ATTEMPTS;
    expect(await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 's2'))).toEqual(
      { status: 'CONFLICT' },
    );
    expect(await storage.get(runKey(ALICE, 's2'))).toBeUndefined();
    const list = await store.listRuns(ALICE);
    expect(list.status === 'OK' && list.items.map((i) => i.run.id)).toEqual(['s1']);
  });

  it('a concurrent writer is merged, not overwritten', async () => {
    const storage = new FlakyStorage();
    const { store, rehearsal } = setup(storage);
    const other = new HistoryStore({ storage, now: () => new Date(T0 + 1000) });
    // The other save lands between our index read and our index write.
    storage.beforeIndexSet = () =>
      other.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 'b'));
    expect(
      (await store.saveRun(ALICE, rehearsal, submit(rehearsal.scenario, COSTLY, 'a'))).status,
    ).toBe('SAVED');
    const list = await store.listRuns(ALICE);
    expect(list.status === 'OK' && list.items.map((i) => i.run.id)).toEqual(['b', 'a']);
  });
});

