function mc62Rehearsal(): TrustedScenario {
  const live: RunbookEvidence = { ...runbook('98305', RB_TITLE, RB_AUTH_STEPS), origin: 'live' };
  const analysis: ChangeAnalysis = analyzeChange(
    change('MC-62', MC62_SUMMARY, MC62_DESCRIPTION, { origin: 'live' }),
    [live],
    AT,
  );
  const result = generateRehearsal({
    analysis,
    findingId: analysis.findings[0]!.id,
    restoreTargetMinutes: 30,
  });
  if (!result.ok) throw new Error(result.message);
  return result.rehearsal;
}

/** What an honest browser would submit after playing `decisions`. */
function submit(
  scenario: SimulationScenario,
  decisions: string[],
  sessionId: string,
): RunSubmission {
  const session = replaySession(scenario, decisions, sessionId, START);
  return {
    sessionId,
    startedAt: START,
    decisionIds: decisions,
    scenarioFingerprint: scenarioFingerprint(scenario),
    evaluation: evaluateSession(scenario, session),
    flags: session.flags,
  };
}

function setup(storage: InMemoryStorage = new InMemoryStorage()) {
  const clock = { now: T0 };
  const store = new HistoryStore({ storage, now: () => new Date(clock.now) });
  return { storage, clock, store, rehearsal: mc62Rehearsal() };
}

/** Rewrites a stored value in place (simulates someone editing storage). */
async function edit<T>(storage: InMemoryStorage, key: string, change: (value: T) => void) {
  const current = (await storage.get<T>(key))!;
  change(current.value);
  expect((await storage.set(key, current.value, current.version)).ok).toBe(true);
  return current.value;
}

/** Edits a record and also fixes up its index digest, so only replay can catch it. */
async function editConsistently<T>(
  storage: InMemoryStorage,
  user: HistoryUser,
  key: string,
  id: string,
  change: (value: T) => void,
) {
  const value = await edit(storage, key, change);
  await edit<HistoryIndex>(storage, indexKey(user), (index) => {
    index.entries.find((e) => e.id === id)!.digest = contentDigest(value);
  });
}

