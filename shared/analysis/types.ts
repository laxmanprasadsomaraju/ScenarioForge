/**
 * M3 contract: change-to-recovery analysis.
 *
 * Owned by the lead. Lane C implements the pure engine against these types,
 * Lane A gathers the live evidence and exposes the resolver, Lane B renders
 * the result. Changes here need the lead's sign-off and tests.
 *
 * Principles:
 * - Every finding quotes its sources verbatim (change text and runbook step).
 * - `confirmed` needs an explicit cross-reference between the change and the
 *   runbook; a text match alone is only `suspected`.
 * - "No findings" never means "ready": it is reported with the coverage that
 *   was actually checked, and anything not read stays `not-assessed`.
 * - No AI in this path. `aiAssisted` is always false for M3 findings.
 */
import type { DataOrigin, EvidenceReference, RecoveryStep } from '../domain/types';

/** A Jira change as read for analysis (fields as written, nothing inferred). */
export interface ChangeEvidence {
  origin: DataOrigin;
  key: string;
  summary: string;
  /** Plain text of the description (ADF flattened), or null when empty. */
  descriptionText: string | null;
  status: string;
  issueType: string;
  updated: string | null;
  /** Relative Jira path, e.g. /browse/MC-10. */
  browsePath: string;
  /** Jira remote links on the issue (e.g. to a Confluence page). */
  remoteLinks: { title: string; url: string }[];
  retrievedAt: string;
}

/** A recovery runbook page as read for analysis. */
export interface RunbookEvidence {
  origin: DataOrigin;
  pageId: string;
  title: string;
  /** Path relative to `<site>/wiki`. */
  webuiPath: string | null;
  lastUpdated: string | null;
  steps: RecoveryStep[];
  stepSource: 'ordered-list' | 'none';
  /** Plain page text, possibly shortened; used for cross-reference checks. */
  text: string;
  retrievedAt: string;
}

/** What a change does to something a runbook may depend on. */
export type ChangeAction = 'retire' | 'replace' | 'migrate' | 'rename' | 'disable' | 'upgrade';

export interface ChangeSubject {
  /** Normalised term as matched, e.g. "legacyauth". */
  term: string;
  /** The term as written in the change. */
  display: string;
  action: ChangeAction;
  /** The sentence from the change that names the term, verbatim. */
  excerpt: string;
  /** Named replacement when the change states one (e.g. "NimbusID"). */
  replacement?: string;
}

/** Why a runbook step is linked to the change. */
export type LinkBasis =
  /** The step's text names a subject of the change. */
  | 'term-match'
  /** The runbook page mentions the change's issue key. */
  | 'page-mentions-issue'
  /** The issue has a remote link to the runbook page. */
  | 'issue-links-page';

export interface ChangeRecoveryFinding {
  id: string;
  changeKey: string;
  pageId: string;
  pageTitle: string;
  stepOrder: number;
  /** Runbook page path relative to `<site>/wiki`, for the source link. */
  pageWebuiPath: string | null;
  subject: ChangeSubject;
  /** `confirmed` only with an explicit cross-reference plus a term match. */
  confidence: 'confirmed' | 'suspected';
  basis: LinkBasis[];
  /** Deterministic template text; never generated by AI. */
  explanation: string;
  /** At least the change excerpt and the runbook step, verbatim. */
  evidence: EvidenceReference[];
  aiAssisted: false;
}

/** A runbook page whose content was read during the analysis. */
export interface CheckedPage {
  pageId: string;
  title: string;
  webuiPath: string | null;
  /** `none`: read, but no numbered list, so no step was checked. */
  stepSource: 'ordered-list' | 'none';
}

export interface AnalysisCoverage {
  /** Recovery pages returned by the search. */
  pagesFound: number;
  /** Pages whose content was actually read. */
  pagesRead: number;
  /** Pages read but without a numbered list (not step-checked). */
  pagesWithoutSteps: number;
  /** Pages found but not read (limits, errors or permissions). */
  pagesSkipped: number;
  /** Exactly the pages that were read, in the order they were checked. */
  pagesChecked: CheckedPage[];
}

export type AnalysisStatus =
  /** At least one finding. */
  | 'findings'
  /** Subjects found and runbooks read, but no step matched. Not "ready". */
  | 'no-findings'
  /** Could not assess: no subjects recognised, nothing readable, or an error. */
  | 'not-assessed';

export interface ChangeAnalysis {
  changeKey: string;
  /** The change as read from Jira, so results always show their source. */
  change: { key: string; summary: string; browsePath: string; updated?: string | null };
  analyzedAt: string;
  status: AnalysisStatus;
  /** Present when status is 'not-assessed'. */
  notAssessedReason?: string;
  subjects: ChangeSubject[];
  findings: ChangeRecoveryFinding[];
  coverage: AnalysisCoverage;
}

/* Resolver contract: `analyzeChange` */

export interface AnalyzeChangeRequest {
  /** Jira issue key, validated server-side. */
  issueKey: string;
}

export type AnalyzeChangeResponse = ChangeAnalysis;

/** Upper bound on runbook pages read per analysis (cost and latency guard). */
export const MAX_RUNBOOKS_READ = 5;
