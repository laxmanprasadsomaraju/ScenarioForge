import type { ExerciseSession, RetestResult, SimulationScenario } from '../domain/types';
import { decisionTrail, evaluateSession, SimulationError } from './engine';
import { applyRemediations } from './remediation';
import { canonicalJson } from './replay';
import type {
  EvaluatedRun,
  GapAssessment,
  ObjectiveComparison,
  RecoveryGap,
  RetestComparison,
  ScenarioRemediationModel,
} from './types';

/**
 * Targeted retest: Remediation -> Retest.
 *
 * `buildRetest` turns approved remediations into the scenario version the team
 * rehearses again. `compareRetest` decides, by explicit rules, whether the
 * retest shows the recovery gap is closed. Both are pure and deterministic.
 */

/**
 * Builds the retest scenario for a completed rehearsal.
 *
 * The original session must be completed and must belong to `originalScenario`
 * (same id and version). An empty remediation list yields an unchanged rerun
 * at the same version.
 */
export function buildRetest(
  originalScenario: SimulationScenario,
  originalSession: ExerciseSession,
  appliedRemediationIds: readonly string[],
  model: ScenarioRemediationModel,
): SimulationScenario {
  assertRunMembership(originalScenario, originalSession, 'Original');
  if (originalSession.status !== 'completed') {
    throw new SimulationError('A retest can only follow a completed exercise.');
  }
  return applyRemediations(originalScenario, model, appliedRemediationIds);
}

export interface CompareRetestOptions {
  /** Id for the RetestResult; generated by the caller, never here. */
  id: string;
  /** Comparison timestamp, passed in so the engine never reads a clock. */
  comparedAt: string;
  /** Limit the comparison to one gap; otherwise every gap in the model is assessed. */
  findingId?: string;
}

/**
 * Compares a retest with the original rehearsal.
 *
 * Preconditions (otherwise throws SimulationError):
 * - both sessions are completed and belong to their scenario (id + version);
 * - both runs use the same scenario id, and the retest version is not older;
 * - each evaluation equals `evaluateSession` recomputed from its session, so a
 *   stale or edited evaluation cannot influence the outcome;
 * - `findingId`, when given, names a gap in the model.
 *
 * Rules, applied per gap using only the retest run:
 * 1. Exercised: the retest took at least one of the gap's `exerciseDecisions`.
 *    If not, the outcome is `inconclusive` — the retest never relied on the
 *    gapped procedure, so it says nothing about whether the fix works, even if
 *    every objective was met.
 * 2. Effective: every exercise decision taken in the retest has assessment
 *    `effective` in the retest scenario.
 * 3. Objectives met: every objective tied to the gap is `met` in the retest
 *    evaluation. An objective missing from the retest evaluation counts as not
 *    met (unknown never becomes a pass).
 * 4. `resolved` only if 1, 2 and 3 all hold; otherwise `still-failing`.
 *
 * Combining gaps (no `findingId`): any `still-failing` gives `still-failing`;
 * otherwise any `inconclusive` gives `inconclusive`; otherwise `resolved`.
 * A model with no gaps gives `inconclusive`.
 *
 * The original run is used for identity checks and for the before/after
 * objective comparison in the report; it does not change the outcome.
 */
export function compareRetest(
  original: EvaluatedRun,
  retest: EvaluatedRun,
  model: ScenarioRemediationModel,
  options: CompareRetestOptions,
): RetestComparison {
  assertEvaluatedRun(original, 'Original');
  assertEvaluatedRun(retest, 'Retest');
  if (original.scenario.id !== retest.scenario.id || model.scenarioId !== original.scenario.id) {
    throw new SimulationError('Original, retest and remediation model must share a scenario id.');
  }
  if (retest.scenario.version < original.scenario.version) {
    throw new SimulationError('Retest scenario version is older than the original.');
  }

  let gaps: RecoveryGap[] = model.gaps;
  if (options.findingId !== undefined) {
    const gap = model.gaps.find((g) => g.findingId === options.findingId);
    if (!gap) throw new SimulationError(`No recovery gap for finding ${options.findingId}.`);
    gaps = [gap];
  }

  const assessments = gaps.map((gap) => assessGap(gap, original, retest));
  const result: RetestResult = {
    id: options.id,
    originalSessionId: original.session.id,
    retestSessionId: retest.session.id,
    outcome: combineOutcomes(assessments.map((a) => a.outcome)),
    comparedAt: options.comparedAt,
  };
  if (options.findingId !== undefined) result.findingId = options.findingId;
  return { ...result, gaps: assessments };
}

function assessGap(gap: RecoveryGap, original: EvaluatedRun, retest: EvaluatedRun): GapAssessment {
  const exerciseKeys = new Set(gap.exerciseDecisions.map((d) => `${d.stepId}/${d.decisionId}`));
  const taken = decisionTrail(retest.scenario, retest.session).filter(({ record }) =>
    exerciseKeys.has(`${record.stepId}/${record.decisionId}`),
  );
  const exercised = taken.length > 0;
  const decisionsEffective =
    exercised && taken.every(({ decision }) => decision.consequence.assessment === 'effective');

  const statusIn = (run: EvaluatedRun, id: string): ObjectiveComparison['retest'] =>
    run.evaluation.objectives.find((o) => o.objectiveId === id)?.status ?? 'absent';
  const objectives = gap.objectiveIds.map((objectiveId): ObjectiveComparison => ({
    objectiveId,
    original: statusIn(original, objectiveId),
    retest: statusIn(retest, objectiveId),
  }));
  const objectivesMet = objectives.every((o) => o.retest === 'met');

  let outcome: RetestResult['outcome'];
  let reason: string;
  if (!exercised) {
    outcome = 'inconclusive';
    reason = 'The retest did not follow the procedure with the gap, so it cannot confirm the fix.';
  } else if (!decisionsEffective) {
    outcome = 'still-failing';
    reason = 'Following the procedure with the gap was still not effective in the retest.';
  } else if (!objectivesMet) {
    const missed = objectives.filter((o) => o.retest !== 'met').map((o) => o.objectiveId);
    outcome = 'still-failing';
    reason = `The procedure worked, but tied objectives were not met: ${missed.join(', ')}.`;
  } else {
    outcome = 'resolved';
    reason = 'The retest followed the corrected procedure and met every tied objective.';
  }
  return {
    findingId: gap.findingId,
    outcome,
    exercised,
    decisionsEffective,
    objectivesMet,
    objectives,
    reason,
  };
}

function combineOutcomes(outcomes: RetestResult['outcome'][]): RetestResult['outcome'] {
  if (outcomes.includes('still-failing')) return 'still-failing';
  if (outcomes.length === 0 || outcomes.includes('inconclusive')) return 'inconclusive';
  return 'resolved';
}

function assertRunMembership(
  scenario: SimulationScenario,
  session: ExerciseSession,
  label: string,
) {
  if (session.scenarioId !== scenario.id || session.scenarioVersion !== scenario.version) {
    throw new SimulationError(`${label} session does not belong to this scenario version.`);
  }
}

function assertEvaluatedRun(run: EvaluatedRun, label: string) {
  assertRunMembership(run.scenario, run.session, label);
  // evaluateSession throws for sessions that are not completed.
  const recomputed = evaluateSession(run.scenario, run.session);
  if (canonicalJson(recomputed) !== canonicalJson(run.evaluation)) {
    throw new SimulationError(`${label} evaluation does not match its session.`);
  }
}
